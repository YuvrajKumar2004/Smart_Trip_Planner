import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'tailwindcss';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const srcDir = path.join(rootDir, 'src');
const themePath = path.join(rootDir, 'node_modules', 'tailwindcss', 'theme.css');
const outPath = path.join(srcDir, 'tailwind.generated.css');

const SOURCE_EXTENSIONS = new Set(['.js', '.jsx', '.ts', '.tsx', '.html']);
const TOKEN_PATTERN = /[A-Za-z0-9_!:\-/.[\]#%(),]+/g;

async function collectFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return collectFiles(fullPath);
    if (SOURCE_EXTENSIONS.has(path.extname(entry.name))) return [fullPath];
    return [];
  }));
  return files.flat();
}

async function collectCandidates() {
  const files = [
    path.join(rootDir, 'index.html'),
    ...(await collectFiles(srcDir)),
  ];
  const candidates = new Set();

  for (const file of files) {
    const content = await fs.readFile(file, 'utf8');
    for (const [token] of content.matchAll(TOKEN_PATTERN)) {
      candidates.add(token);
    }
  }

  return [...candidates].sort();
}

const themeCss = await fs.readFile(themePath, 'utf8');
const compiler = await compile(`
${themeCss}

@theme {
  --font-display: "Clash Display", sans-serif;
  --font-body: "Cabinet Grotesk", sans-serif;
}

@tailwind utilities;
`);

const candidates = await collectCandidates();
const css = compiler.build(candidates);

await fs.writeFile(outPath, `/* Generated by scripts/generate-tailwind-css.mjs. */\n${css}`, 'utf8');
console.log(`Generated ${path.relative(rootDir, outPath)} from ${candidates.length} candidates.`);
